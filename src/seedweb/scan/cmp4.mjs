import fs from 'fs';
const sc=JSON.parse(fs.readFileSync('/tmp/reg/scan.json')); const C=JSON.parse(fs.readFileSync('/tmp/reg/cand.json'));
const loaded=new Set();for(let i=0;i<sc.cl.length;i+=2)loaded.add(sc.cl[i]+','+sc.cl[i+1]);
const all=sc.lavaIn.concat(sc.lavaSky);
const cs=C.filter(c=>c[0]===0&&loaded.has((c[1]>>4)+','+(c[3]>>4))&&c[4]&&c[6]);
const hit=(q)=>all.some(c=>c[0]>=q[1]-9&&c[0]<=q[1]+8&&c[2]>=q[3]-9&&c[2]<=q[3]+8&&c[1]>=q[2]-6&&c[1]<=q[2]+1);
const fps=cs.filter(c=>!hit(c)), tps=cs.filter(hit);
const near=q=>{let b=null,bd=1e9;for(const c of all){const d=Math.hypot(c[0]-q[1],c[2]-q[3]);if(d<bd){bd=d;b=c}}return [Math.round(bd),b];};
console.log('TP y dist', tps.slice(0,10).map(c=>c[2]+'/'+c[7]).join(' '));
console.log('FP y/surf', fps.slice(0,25).map(c=>c[2]+'/'+c[7]).join(' '));
console.log('FP nearest', fps.slice(0,12).map(c=>JSON.stringify([c[1],c[2],c[3],near(c)])).join('\n'));
const hist=a=>{const h={};for(const c of a){const k=Math.floor(c[2]/10)*10;h[k]=(h[k]||0)+1}return JSON.stringify(h)};
console.log('TP y hist',hist(tps)); console.log('FP y hist',hist(fps));
